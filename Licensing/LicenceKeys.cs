namespace VibranceHud.Licensing
{
    /// <summary>
    /// The key PlexusX uses to check that a licence is genuine.
    ///
    /// This is the PUBLIC half, and it is meant to be here. It can confirm a signature; it
    /// cannot produce one. Someone who decompiles PlexusX and lifts every byte of this file
    /// gains the ability to verify licences, which buys them nothing. That is the entire point
    /// of the redesign: the beta shipped a symmetric secret, so possessing the app meant
    /// possessing the power to mint keys.
    ///
    /// The private half exists in one place, on one machine, inside PlexusX Keys. It is never
    /// committed, never published, and never sent anywhere.
    ///
    /// Changing these bytes invalidates every licence ever issued. There is no reason to touch
    /// them short of a key compromise, and that would mean re-issuing licences to every paying
    /// customer by hand.
    /// </summary>
